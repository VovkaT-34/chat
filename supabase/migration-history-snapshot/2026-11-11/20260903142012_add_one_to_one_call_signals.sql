create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  chat_id bigint not null references public.chats(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  call_id uuid not null,
  signal_type text not null check (signal_type in ('offer','answer','ice','reject','hangup')),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists call_signals_recipient_id_created_at_idx
  on public.call_signals(recipient_id, created_at desc);
create index if not exists call_signals_call_id_created_at_idx
  on public.call_signals(call_id, created_at asc);

alter table public.call_signals enable row level security;

create policy "call_signals_select_participants"
on public.call_signals for select
to authenticated
using (
  sender_id = (select auth.uid())
  or recipient_id = (select auth.uid())
);

create policy "call_signals_insert_sender"
on public.call_signals for insert
to authenticated
with check (
  sender_id = (select auth.uid())
  and exists (
    select 1 from public.chat_members cm
    where cm.chat_id = call_signals.chat_id
      and cm.user_id = (select auth.uid())
  )
  and exists (
    select 1 from public.chat_members cm
    where cm.chat_id = call_signals.chat_id
      and cm.user_id = call_signals.recipient_id
  )
  and sender_id <> recipient_id
);

create policy "call_signals_delete_participants"
on public.call_signals for delete
to authenticated
using (
  sender_id = (select auth.uid())
  or recipient_id = (select auth.uid())
);

grant select, insert, delete on public.call_signals to authenticated;
grant usage, select on sequence public.call_signals_id_seq to authenticated;

alter publication supabase_realtime add table public.call_signals;
