-- Persistent, per-user-visible system events for disappearing-message timer changes.
CREATE TABLE public.chat_disappearing_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint NOT NULL REFERENCES public.chats(id) ON DELETE CASCADE,
    actor_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
    actor_name text NOT NULL,
    actor_role_label text,
    mode text NOT NULL CHECK (mode IN ('self', 'all')),
    enabled boolean NOT NULL,
    duration_seconds integer NOT NULL CHECK (duration_seconds IN (30,300,3600,10800,86400,259200,604800)),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX chat_disappearing_events_chat_created_idx ON public.chat_disappearing_events(chat_id, created_at);
ALTER TABLE public.chat_disappearing_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.chat_disappearing_events FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.chat_disappearing_events TO authenticated;
CREATE POLICY authenticated_select_visible_chat_disappearing_events
ON public.chat_disappearing_events FOR SELECT TO authenticated
USING (
    (SELECT public.is_approved_user())
    AND EXISTS (SELECT 1 FROM public.chat_members cm WHERE cm.chat_id=chat_disappearing_events.chat_id AND cm.user_id=(SELECT auth.uid()))
    AND (mode='all' OR (mode='self' AND actor_id=(SELECT auth.uid())))
);
CREATE OR REPLACE FUNCTION public.get_chat_disappearing_events(p_chat_id bigint)
RETURNS TABLE (id bigint,chat_id bigint,actor_id uuid,actor_name text,actor_role_label text,mode text,enabled boolean,duration_seconds integer,created_at timestamptz)
LANGUAGE sql STABLE SECURITY INVOKER SET search_path=''
AS $function$
    SELECT e.id,e.chat_id,e.actor_id,e.actor_name,e.actor_role_label,e.mode,e.enabled,e.duration_seconds,e.created_at
    FROM public.chat_disappearing_events e
    WHERE e.chat_id=p_chat_id
      AND (SELECT public.is_approved_user())
      AND EXISTS (SELECT 1 FROM public.chat_members cm WHERE cm.chat_id=e.chat_id AND cm.user_id=(SELECT auth.uid()))
      AND (e.mode='all' OR (e.mode='self' AND e.actor_id=(SELECT auth.uid())))
    ORDER BY e.created_at ASC,e.id ASC;
$function$;
REVOKE ALL ON FUNCTION public.get_chat_disappearing_events(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_chat_disappearing_events(bigint) TO authenticated;
CREATE OR REPLACE FUNCTION public.set_chat_disappearing_settings(p_chat_id bigint,p_mode text,p_enabled boolean,p_duration_seconds integer)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE
    v_uid uuid:=(SELECT auth.uid());
    v_type text;
    v_is_group boolean;
    v_owner uuid;
    v_member_count integer;
    v_old_enabled boolean;
    v_old_duration integer;
    v_changed boolean:=false;
    v_actor_name text;
    v_actor_role_label text;
BEGIN
    IF v_uid IS NULL OR NOT public.is_approved_user() THEN RAISE EXCEPTION 'Пользователь не авторизован или аккаунт не одобрен'; END IF;
    IF p_mode IS NULL OR p_mode NOT IN ('self','all') OR p_enabled IS NULL OR p_duration_seconds IS NULL
       OR p_duration_seconds NOT IN (30,300,3600,10800,86400,259200,604800) THEN
        RAISE EXCEPTION 'Некорректные параметры исчезающих сообщений';
    END IF;
    SELECT c.type,c.is_group,c.created_by,(SELECT count(*)::integer FROM public.chat_members cm WHERE cm.chat_id=c.id)
    INTO v_type,v_is_group,v_owner,v_member_count FROM public.chats c WHERE c.id=p_chat_id;
    IF NOT FOUND OR v_type<>'private' THEN RAISE EXCEPTION 'Настройка доступна только в личных и групповых чатах'; END IF;
    IF NOT EXISTS(SELECT 1 FROM public.chat_members cm WHERE cm.chat_id=p_chat_id AND cm.user_id=v_uid) THEN RAISE EXCEPTION 'Нет доступа к этому чату'; END IF;
    IF NOT v_is_group AND v_member_count<>2 THEN RAISE EXCEPTION 'Настройка доступна только в личном чате один на один'; END IF;
    IF p_mode='all' THEN
        IF v_is_group AND v_owner IS DISTINCT FROM v_uid THEN RAISE EXCEPTION 'Только владелец группы может управлять исчезновением для всех'; END IF;
        SELECT s.enabled,s.duration_seconds INTO v_old_enabled,v_old_duration FROM public.chat_disappearing_settings s WHERE s.chat_id=p_chat_id;
        v_changed:=NOT FOUND OR v_old_enabled IS DISTINCT FROM p_enabled OR v_old_duration IS DISTINCT FROM p_duration_seconds;
        INSERT INTO public.chat_disappearing_settings(chat_id,enabled,duration_seconds,updated_by,updated_at)
        VALUES(p_chat_id,p_enabled,p_duration_seconds,v_uid,now())
        ON CONFLICT(chat_id) DO UPDATE SET enabled=EXCLUDED.enabled,duration_seconds=EXCLUDED.duration_seconds,updated_by=EXCLUDED.updated_by,updated_at=now();
    ELSE
        SELECT s.enabled,s.duration_seconds INTO v_old_enabled,v_old_duration FROM public.user_chat_disappearing_settings s WHERE s.chat_id=p_chat_id AND s.user_id=v_uid;
        v_changed:=NOT FOUND OR v_old_enabled IS DISTINCT FROM p_enabled OR v_old_duration IS DISTINCT FROM p_duration_seconds;
        INSERT INTO public.user_chat_disappearing_settings(chat_id,user_id,enabled,duration_seconds,updated_at)
        VALUES(p_chat_id,v_uid,p_enabled,p_duration_seconds,now())
        ON CONFLICT(chat_id,user_id) DO UPDATE SET enabled=EXCLUDED.enabled,duration_seconds=EXCLUDED.duration_seconds,updated_at=now();
        -- Personal timers continue to apply to new messages only.
    END IF;
    IF v_changed THEN
        SELECT COALESCE(NULLIF(p.username,''),'Пользователь'),
               CASE WHEN p.role IN ('admin','superadmin') OR (v_is_group AND v_owner=v_uid) THEN 'администратор' ELSE NULL END
        INTO v_actor_name,v_actor_role_label FROM public.profiles p WHERE p.id=v_uid;
        INSERT INTO public.chat_disappearing_events(chat_id,actor_id,actor_name,actor_role_label,mode,enabled,duration_seconds)
        VALUES(p_chat_id,v_uid,COALESCE(v_actor_name,'Пользователь'),v_actor_role_label,p_mode,p_enabled,p_duration_seconds);
    END IF;
END;
$function$;
REVOKE ALL ON FUNCTION public.set_chat_disappearing_settings(bigint,text,boolean,integer) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.set_chat_disappearing_settings(bigint,text,boolean,integer) TO authenticated;
DO $publication$
BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.chat_disappearing_events;
EXCEPTION WHEN duplicate_object THEN NULL;
END;
$publication$;
