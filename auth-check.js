
// =========================================
// Проверка авторизации через Supabase
// =========================================

async function checkAuth() {

    try {

        // =========================================
        // Получаем текущую сессию
        // =========================================

        const {
            data: {
                session
            }
        } = await supabaseClient.auth.getSession();


        // =========================================
        // Если пользователь не вошёл
        // =========================================

        if (!session) {

            window.location.replace(
                "./login.html"
            );

            return;

        }


        // =========================================
        // Получаем профиль через RPC
        // =========================================
        //
        // Прямого SELECT из profiles больше нет.
        // Проверка выполняется через
        // SECURITY DEFINER функцию
        // check_my_profile().
        //

        const {
            data: profile,
            error
        } = await supabaseClient.rpc(
            "check_my_profile"
        );


        // =========================================
        // Если профиль не получен
        // =========================================

        if (
            error ||
            !profile ||
            !profile[0]
        ) {

            console.error(
                "Ошибка проверки профиля:",
                error
            );

            await supabaseClient.auth.signOut();

            window.location.replace(
                "./login.html"
            );

            return;

        }


        // =========================================
        // Получаем данные профиля
        // =========================================

        const userProfile =
            profile[0];


        // =========================================
        // Если аккаунт не подтверждён
        // =========================================

        if (!userProfile.approved) {

            await supabaseClient.auth.signOut();

            window.location.replace(
                "./login.html"
            );

            return;

        }


        // =========================================
        // Пользователь авторизован
        // и имеет подтверждённый аккаунт.
        // =========================================

    } catch (error) {

        console.error(
            "Ошибка проверки авторизации:",
            error
        );

        window.location.replace(
            "./login.html"
        );

    }

}


// =========================================
// Запускаем проверку
// =========================================

checkAuth();

